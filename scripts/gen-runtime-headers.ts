/**
 * Generates the C headers the runtime shares with the tools, from the two
 * data files under gamedata/:
 *
 *   contract.json -> runtime/sdk/include/mh_contract.h     (public: API version, events, levels)
 *                    runtime/src/generated/mh_contract_data.h (internal: level names, override limits)
 *   catalog.json  -> runtime/src/generated/mh_catalog_data.h  (entity names, stage bindings, sounds)
 *
 *   npx tsx scripts/gen-runtime-headers.ts [--check]
 *
 * With --check nothing is written; the script fails if a header is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const read = (path: string) => JSON.parse(readFileSync(join(root, path), 'utf8'));
const NOTE = '/* Generated by scripts/gen-runtime-headers.ts. Do not hand-edit. */';

/** A C string literal; non-ASCII is escaped the way JSON does it. */
const cString = (value: unknown): string => JSON.stringify(String(value)).replace(/[\u0080-￿]/g, (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`);

function contractHeaders(c: any): { publicHeader: string; internalHeader: string } {
  const { events, levels, coordinates: coord } = c;
  const pkg = c.package;
  const pub: string[] = [
    '#ifndef MH_CONTRACT_H',
    '#define MH_CONTRACT_H',
    '',
    NOTE,
    `#define MH_API_VERSION ${c.api_version}u`,
    `#define MH_PACKAGE_FORMAT "${pkg.format}"`,
    `#define MH_PACKAGE_MANIFEST "${pkg.manifest}"`,
    `#define MH_PACKAGE_NATIVE_ENTRY "${pkg.native_entry}"`,
    `#define MH_PACKAGE_SCRIPT_ENTRY "${pkg.script_entry}"`,
    `#define MH_PACKAGE_MAPS_DIR "${pkg.maps_dir}"`,
    `#define MH_PACKAGE_ASSETS_DIR "${pkg.assets_dir}"`,
    `#define MH_PACKAGE_ARCHIVE_DIR "${pkg.archive_dir}"`,
    `#define MH_PACKAGE_AUDIO_DIR "${pkg.audio_dir}"`,
    `#define MH_PACKAGE_SETTINGS_FILE "${pkg.settings_file}"`,
    `#define MH_MAP_SUBUNITS_PER_CELL ${coord.map_subunits_per_cell}u`,
    `#define MH_WORLD_ONE ${coord.world_units_per_cell}L`,
    `#define MH_FACING_PERIOD ${coord.facing_period}u`,
    '',
    'typedef enum MHEventType {',
    '    MH_EVENT_NONE = 0,',
  ];
  for (const e of events) pub.push(`    MH_EVENT_${e.name} = ${e.value},`);
  pub.push('} MHEventType;', '', '#define MH_EVENT_MASK(event_type) (1u << ((unsigned long)(event_type) - 1u))');
  for (const e of events) pub.push(`#define MH_EVENT_MASK_${e.name} MH_EVENT_MASK(MH_EVENT_${e.name})`);
  pub.push(`#define MH_EVENT_MASK_ALL 0x${((1 << events.length) - 1).toString(16).padStart(8, '0')}u`);
  pub.push('', 'typedef enum MHLevel {', '    MH_LEVEL_INVALID = -1,');
  for (const level of levels) pub.push(`    MH_LEVEL_${level.id} = ${level.index},`);
  pub.push(`    MH_LEVEL_COUNT = ${levels.length}`, '} MHLevel;', '', `#define MH_SINGLE_PLAYER_LEVEL_COUNT ${levels.filter((l: any) => l.single_player).length}u`, '', '#endif', '');

  const generic: any[] = c.generic_archive_overrides ?? [];
  const special: any[] = c.specialized_archive_overrides ?? [];
  const int: string[] = ['#ifndef MH_CONTRACT_DATA_H', '#define MH_CONTRACT_DATA_H', '', NOTE, `static const char *const MH_LEVEL_NAMES[${levels.length}] = {`];
  for (const level of levels) int.push(`    "${level.id}",`);
  int.push(
    '};',
    '',
    'typedef struct MHGeneratedArchiveOverrideContract {',
    '    const char *extension;',
    '    unsigned long min_size;',
    '    unsigned long max_size;',
    '} MHGeneratedArchiveOverrideContract;',
    '',
    `#define MH_GENERIC_ARCHIVE_OVERRIDE_COUNT ${generic.length}u`,
    `static const MHGeneratedArchiveOverrideContract MH_GENERIC_ARCHIVE_OVERRIDES[${Math.max(1, generic.length)}] = {`,
  );
  for (const item of generic) int.push(`    {"${item.extension}",${item.min_size}u,${item.max_size}u},`);
  if (!generic.length) int.push('    {"",0u,0u},');
  int.push('};', '');
  const terrain = special.find((x) => x.kind === 'terrain');
  if (terrain) {
    int.push(
      `#define MH_TERRAIN_ARCHIVE_EXTENSION "${terrain.extension}"`,
      `#define MH_TERRAIN_MAX_TILES ${terrain.max_tiles}u`,
      `#define MH_TERRAIN_TILE_BYTES ${terrain.tile_bytes}u`,
      '#define MH_TERRAIN_MAX_DECODED_BYTES (4u + MH_TERRAIN_MAX_TILES*4u + MH_TERRAIN_MAX_TILES*MH_TERRAIN_TILE_BYTES)',
      '',
    );
  }
  const sprite = special.find((x) => x.kind === 'sprite');
  if (sprite) {
    int.push(`#define MH_SPRITE_ARCHIVE_EXTENSION "${sprite.extension}"`, `#define MH_SPRITE_MAX_FRAMES ${sprite.max_frames}u`, `#define MH_SPRITE_MAX_FILE_BYTES ${sprite.max_file_bytes}u`, `#define MH_SPRITE_ARENA_BYTES ${sprite.arena_bytes}u`, '');
  }
  const bitmap = special.find((x) => x.kind === 'bitmap');
  if (bitmap) {
    int.push(
      `#define MH_BITMAP_ARCHIVE_EXTENSION "${bitmap.extension}"`,
      `#define MH_BITMAP_MAX_FILE_BYTES ${bitmap.max_file_bytes}u`,
      `#define MH_BITMAP_BPP ${bitmap.bpp}u`,
      `#define MH_BITMAP_COMPRESSION ${bitmap.compression}u`,
      `#define MH_BITMAP_PALETTE_ENTRIES ${bitmap.palette_entries}u`,
      '',
    );
  }
  int.push('#endif', '');
  return { publicHeader: pub.join('\n'), internalHeader: int.join('\n') };
}

function catalogHeader(catalog: any): string {
  const entities: any[] = catalog.entities;
  const stages: any[] = catalog.stages;
  const names: string[] = Array(256).fill('(const char *)0');
  for (const e of entities) if (e.map_type >= 0 && e.map_type < 256) names[e.map_type] = cString(e.name);

  const flatResources: [number, string, number, string][] = [];
  const flatSprites: [number, number, number, number, string][] = [];
  const flatAmbient: any[] = [];
  const ro: number[] = [];
  const rc: number[] = [];
  const so: number[] = [];
  const sc: number[] = [];
  const ao: number[] = [];
  const ac: number[] = [];
  stages.forEach((_, level) => {
    ao.push(flatAmbient.length);
    flatAmbient.push(...catalog.ambient_sound_profiles.filter((p: any) => p.level_index === level));
    ac.push(flatAmbient.length - ao[level]);
  });
  for (const st of stages) {
    ro.push(flatResources.length);
    for (const [role, r] of Object.entries<any>(st.resources)) flatResources.push([st.stage, role, r.archive_id, r.name]);
    rc.push(flatResources.length - ro[ro.length - 1]);
    so.push(flatSprites.length);
    for (const b of st.spriteResources) flatSprites.push([st.stage, b.list_index, b.archive_id, b.runtime_slot, b.name]);
    sc.push(flatSprites.length - so[so.length - 1]);
  }
  const list = (values: number[]) => values.map((v) => `${v}u`).join(',');

  const lines: string[] = [
    '#ifndef MH_CATALOG_DATA_H',
    '#define MH_CATALOG_DATA_H',
    '',
    NOTE,
    `#define MH_ENTITY_CATALOG_COUNT ${entities.length}u`,
    `static const unsigned short MH_ENTITY_CATALOG_TYPES[MH_ENTITY_CATALOG_COUNT] = {${entities.map((e) => `${e.map_type}u`).join(',')}};`,
    'static const char *const MH_ENTITY_NAMES_BY_TYPE[256] = {',
  ];
  for (let i = 0; i < 256; i += 8) lines.push(`    ${names.slice(i, i + 8).join(', ')},`);
  lines.push(
    '};',
    '',
    'typedef struct MHGeneratedStageResource {',
    '    unsigned long level;',
    '    const char *role;',
    '    unsigned long archive_id;',
    '    const char *name;',
    '} MHGeneratedStageResource;',
    '',
    'typedef struct MHGeneratedStageSprite {',
    '    unsigned long level;',
    '    unsigned long binding_index;',
    '    unsigned long archive_id;',
    '    unsigned long runtime_slot;',
    '    const char *name;',
    '} MHGeneratedStageSprite;',
    '',
    `#define MH_STAGE_CATALOG_COUNT ${stages.length}u`,
    `#define MH_STAGE_RESOURCE_COUNT ${flatResources.length}u`,
    `#define MH_STAGE_SPRITE_BINDING_COUNT ${flatSprites.length}u`,
    'static const MHGeneratedStageResource MH_STAGE_RESOURCES[MH_STAGE_RESOURCE_COUNT] = {',
  );
  for (const [level, role, id, name] of flatResources) lines.push(`    {${level}u, ${cString(role)}, ${id}u, ${cString(name)}},`);
  lines.push('};', `static const unsigned short MH_STAGE_RESOURCE_OFFSETS[MH_STAGE_CATALOG_COUNT] = {${list(ro)}};`, `static const unsigned char MH_STAGE_RESOURCE_COUNTS[MH_STAGE_CATALOG_COUNT] = {${list(rc)}};`, '', 'static const MHGeneratedStageSprite MH_STAGE_SPRITES[MH_STAGE_SPRITE_BINDING_COUNT] = {');
  for (const [level, index, id, slot, name] of flatSprites) lines.push(`    {${level}u, ${index}u, ${id}u, ${slot}u, ${cString(name)}},`);
  lines.push('};', `static const unsigned short MH_STAGE_SPRITE_OFFSETS[MH_STAGE_CATALOG_COUNT] = {${list(so)}};`, `static const unsigned char MH_STAGE_SPRITE_COUNTS[MH_STAGE_CATALOG_COUNT] = {${list(sc)}};`, '');
  lines.push(
    'typedef struct MHGeneratedAmbientProfile {',
    '    unsigned long level;',
    '    unsigned long selector;',
    '    unsigned long mode;',
    '    unsigned long sound_id;',
    '    const char *sample_name;',
    '    unsigned short base_delay;',
    '    unsigned short random_range;',
    '    unsigned long retail_uses;',
    '} MHGeneratedAmbientProfile;',
    '',
    `#define MH_AMBIENT_PROFILE_COUNT ${flatAmbient.length}u`,
    'static const MHGeneratedAmbientProfile MH_AMBIENT_PROFILES[MH_AMBIENT_PROFILE_COUNT] = {',
  );
  for (const p of flatAmbient) {
    lines.push(`    {${p.level_index}u, ${p.selector}u, ${p.mode}u, ${p.sound_id}u, ${p.sample_name ? cString(p.sample_name) : '(const char *)0'}, ${p.base_delay}u, ${p.random_range}u, ${p.type39_retail_uses}u},`);
  }
  lines.push('};', `static const unsigned short MH_AMBIENT_PROFILE_OFFSETS[MH_STAGE_CATALOG_COUNT] = {${list(ao)}};`, `static const unsigned char MH_AMBIENT_PROFILE_COUNTS[MH_STAGE_CATALOG_COUNT] = {${list(ac)}};`, '');
  lines.push('typedef struct MHGeneratedSpriteContainer {', '    const char *name;', '    unsigned long bytes;', '    unsigned long frames;', '} MHGeneratedSpriteContainer;', '', `#define MH_SPRITE_CONTAINER_COUNT ${catalog.spriteContainers.length}u`, 'static const MHGeneratedSpriteContainer MH_SPRITE_CONTAINERS[MH_SPRITE_CONTAINER_COUNT] = {');
  for (const s of catalog.spriteContainers) lines.push(`    {${cString(s.name)}, ${s.bytes}u, ${s.frames}u},`);
  lines.push('};', '');
  lines.push(
    'typedef struct MHGeneratedBitmapResource {',
    '    const char *name;',
    '    unsigned long bytes;',
    '    unsigned short width;',
    '    unsigned short height;',
    '    unsigned short bpp;',
    '} MHGeneratedBitmapResource;',
    '',
    `#define MH_BITMAP_RESOURCE_COUNT ${catalog.bitmapResources.length}u`,
    'static const MHGeneratedBitmapResource MH_BITMAP_RESOURCES[MH_BITMAP_RESOURCE_COUNT] = {',
  );
  for (const b of catalog.bitmapResources) lines.push(`    {${cString(b.name)}, ${b.bytes}u, ${b.width}u, ${b.height}u, ${b.bpp}u},`);
  lines.push('};', '');
  lines.push('typedef struct MHGeneratedSoundEffect {', '    unsigned short effect_id;', '    const char *sample_name;', '} MHGeneratedSoundEffect;', '', `#define MH_SOUND_EFFECT_COUNT ${catalog.soundEffects.length}u`, 'static const MHGeneratedSoundEffect MH_SOUND_EFFECTS[MH_SOUND_EFFECT_COUNT] = {');
  for (const s of catalog.soundEffects) lines.push(`    {${s.effect_id}u, ${cString(s.sample_name)}},`);
  lines.push('};', '', '#endif', '');
  return lines.join('\n');
}

const contract = contractHeaders(read('gamedata/contract.json'));
const outputs: [string, string][] = [
  ['runtime/sdk/include/mh_contract.h', contract.publicHeader],
  ['runtime/src/generated/mh_contract_data.h', contract.internalHeader],
  ['runtime/src/generated/mh_catalog_data.h', catalogHeader(read('gamedata/catalog.json'))],
];

let stale = 0;
for (const [path, text] of outputs) {
  const full = join(root, path);
  let current = '';
  try {
    current = readFileSync(full, 'utf8');
  } catch {
    /* not generated yet */
  }
  if (current === text) continue;
  stale++;
  if (!check) writeFileSync(full, text);
  console.log(`${check ? 'stale' : 'wrote'} ${relative(root, full)}`);
}
if (check && stale) process.exit(1);
if (!stale) console.log('runtime headers are up to date');
